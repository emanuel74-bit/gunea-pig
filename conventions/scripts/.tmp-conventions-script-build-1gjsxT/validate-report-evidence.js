import fs from "node:fs";
import path from "node:path";
import { finish, issue, readYamlFile, resolveConventionsRoot, writeYamlFile } from "./lib/common.js";
const SCRIPT_ID = "validate-report-evidence";
const root = resolveConventionsRoot();
const issues = [];
const indexPath = path.join(root, ".ai", "reports", "evidence-index.yaml");
if (!fs.existsSync(indexPath)) {
    issues.push(issue("critical", "EVIDENCE_INDEX_MISSING", "Evidence index is missing; run collect_evidence before validating report evidence."));
}
else {
    const index = readYamlFile(indexPath);
    if (index.generated_by !== "collect-evidence") {
        issues.push(issue("error", "EVIDENCE_INDEX_NOT_SCRIPT_PRODUCED", "Evidence index must be generated by collect-evidence.", ".ai/reports/evidence-index.yaml"));
    }
    if (!Array.isArray(index.entries)) {
        issues.push(issue("error", "EVIDENCE_INDEX_ENTRIES_INVALID", "Evidence index entries must be a list.", ".ai/reports/evidence-index.yaml"));
    }
    else {
        for (const entry of index.entries) {
            const entryPath = String(entry?.path ?? "");
            if (!entryPath.startsWith(".ai/")) {
                issues.push(issue("error", "EVIDENCE_ENTRY_PATH_INVALID", `Evidence entry path must be a .ai artifact path: ${entryPath}`));
                continue;
            }
            if (!fs.existsSync(path.join(root, entryPath))) {
                issues.push(issue("error", "EVIDENCE_ENTRY_TARGET_MISSING", `Evidence entry target does not exist: ${entryPath}`));
            }
            if (!entry.generated_by || String(entry.generated_by) === "unknown") {
                issues.push(issue("warning", "EVIDENCE_ENTRY_GENERATOR_UNKNOWN", `Evidence entry does not identify a script generator: ${entryPath}`));
            }
        }
    }
}
const reportDir = path.join(root, ".ai", "reports");
const reportFiles = fs.existsSync(reportDir)
    ? fs.readdirSync(reportDir).filter(name => name.endsWith(".yaml") || name.endsWith(".yml"))
    : [];
for (const name of reportFiles) {
    if (["evidence-index.yaml", "evidence-collection-report.yaml", "report-evidence-validation.yaml"].includes(name))
        continue;
    const reportPath = path.join(reportDir, name);
    const report = readYamlFile(reportPath);
    const relative = `.ai/reports/${name}`;
    if (relative === ".ai/reports/final-mission-report.yaml" && report.generated_by !== "generate-final-mission-report") {
        issues.push(issue("error", "FINAL_REPORT_NOT_SCRIPT_PRODUCED", "Final mission report must be generated by generate-final-mission-report.", relative));
    }
    if (report.generated_by && Array.isArray(report.evidence_refs)) {
        for (const ref of report.evidence_refs) {
            if (typeof ref !== "string" || !ref.startsWith(".ai/")) {
                issues.push(issue("error", "REPORT_EVIDENCE_REF_INVALID", `Report evidence reference must be a .ai path: ${String(ref)}`, relative));
            }
            else if (!fs.existsSync(path.join(root, ref))) {
                issues.push(issue("error", "REPORT_EVIDENCE_REF_MISSING", `Report evidence reference does not exist: ${ref}`, relative));
            }
        }
    }
}
const validationReport = {
    artifact: "report_evidence_validation_report",
    generated_by: SCRIPT_ID,
    status: issues.some(i => i.severity === "error" || i.severity === "critical") ? "fail" : "pass",
    checked_evidence_index: fs.existsSync(indexPath),
    checked_report_count: reportFiles.length,
};
writeYamlFile(path.join(root, ".ai", "reports", "report-evidence-validation.yaml"), validationReport);
finish(SCRIPT_ID, issues, [".ai/validation/validate-report-evidence.result.yaml", ".ai/reports/report-evidence-validation.yaml"], validationReport);
