import fs from "node:fs";
import path from "node:path";
import { asArray, finish, issue, readExecutorRoutes, readYamlFile, resolveConventionsRoot, writeYamlFile } from "./lib/common.js";
const SCRIPT_ID = "validate-claude-execution-plan";
const root = resolveConventionsRoot();
const issues = [];
const planPath = path.join(root, ".ai", "claude", "execution-plan.yaml");
const routes = readExecutorRoutes(root);
if (!fs.existsSync(planPath)) {
    issues.push(issue("critical", "CLAUDE_EXECUTION_PLAN_MISSING", "Claude execution plan is missing; run generate_claude_execution_plan first.", ".ai/claude/execution-plan.yaml"));
}
else {
    const plan = readYamlFile(planPath);
    if (plan.generated_by !== "generate-claude-execution-plan") {
        issues.push(issue("error", "CLAUDE_EXECUTION_PLAN_NOT_SCRIPT_PRODUCED", "Claude execution plan must be generated by generate-claude-execution-plan.", ".ai/claude/execution-plan.yaml"));
    }
    if (plan.route_resolution_authority !== "executors/conventions.executor-routes.yaml") {
        issues.push(issue("error", "CLAUDE_ROUTE_AUTHORITY_INVALID", "Claude execution plan must cite central executor routes as route authority.", ".ai/claude/execution-plan.yaml"));
    }
    const requiredSections = ["mission_start_routes", "phase_execution_routes", "completion_routes", "route_contract_slices", "stop_conditions", "completion_requires"];
    for (const section of requiredSections) {
        if (!(section in plan))
            issues.push(issue("error", "CLAUDE_PLAN_SECTION_MISSING", `Claude execution plan missing ${section}.`, ".ai/claude/execution-plan.yaml"));
    }
    const allPlanRoutes = [...asArray(plan.mission_start_routes), ...asArray(plan.phase_execution_routes), ...asArray(plan.completion_routes)];
    for (const routeId of allPlanRoutes) {
        if (!routes.has(routeId)) {
            issues.push(issue("error", "CLAUDE_PLAN_UNKNOWN_ROUTE", `Claude execution plan references unknown route: ${routeId}`, ".ai/claude/execution-plan.yaml"));
        }
        if (!plan.route_contract_slices?.[routeId]) {
            issues.push(issue("error", "CLAUDE_PLAN_ROUTE_SLICE_MISSING", `Claude execution plan missing route slice for ${routeId}`, ".ai/claude/execution-plan.yaml"));
        }
    }
    for (const routeId of ["generate_phase_bundle", "validate_phase_bundle", "run_gate_check", "validate_gate_result", "prepare_agent_handoff", "validate_handoff", "collect_evidence", "validate_report_evidence", "generate_final_mission_report"]) {
        if (!allPlanRoutes.includes(routeId)) {
            issues.push(issue("error", "CLAUDE_PLAN_REQUIRED_ROUTE_MISSING", `Claude execution plan must include required route ${routeId}`, ".ai/claude/execution-plan.yaml"));
        }
    }
    const forbiddenText = JSON.stringify(plan).toLowerCase();
    for (const forbidden of ["manual_gate_pass", "manual_handoff_packet", "manual_revision_decision", "manual_final_report"]) {
        if (forbiddenText.includes(forbidden)) {
            issues.push(issue("error", "CLAUDE_PLAN_FORBIDDEN_MANUAL_AUTHORITY", `Claude execution plan contains forbidden manual authority marker: ${forbidden}`, ".ai/claude/execution-plan.yaml"));
        }
    }
}
const report = {
    artifact: "claude_execution_plan_validation_report",
    generated_by: SCRIPT_ID,
    status: issues.some(entry => entry.severity === "error" || entry.severity === "critical") ? "fail" : "pass",
    checked_plan: fs.existsSync(planPath),
};
writeYamlFile(path.join(root, ".ai", "reports", "claude-execution-plan-validation.yaml"), report);
finish(SCRIPT_ID, issues, [".ai/validation/validate-claude-execution-plan.result.yaml", ".ai/reports/claude-execution-plan-validation.yaml"], report);
