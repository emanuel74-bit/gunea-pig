import fs from "node:fs";
import path from "node:path";
import { finish, issue, readYamlFile, resolveConventionsRoot, writeYamlFile } from "./lib/common.js";
const SCRIPT_ID = "generate-final-mission-report";
const root = resolveConventionsRoot();
const issues = [];
const evidencePath = path.join(root, ".ai", "reports", "evidence-index.yaml");
let evidenceIndex = { entries: [] };
if (!fs.existsSync(evidencePath)) {
    issues.push(issue("critical", "EVIDENCE_INDEX_MISSING", "Cannot generate final mission report without evidence-index.yaml; run collect_evidence first."));
}
else {
    evidenceIndex = readYamlFile(evidencePath);
    if (evidenceIndex.generated_by !== "collect-evidence") {
        issues.push(issue("error", "EVIDENCE_INDEX_NOT_SCRIPT_PRODUCED", "Final mission report requires an evidence index generated by collect-evidence."));
    }
    if (!Array.isArray(evidenceIndex.entries)) {
        issues.push(issue("error", "EVIDENCE_INDEX_ENTRIES_INVALID", "Evidence index entries must be a list."));
        evidenceIndex.entries = [];
    }
}
const entries = Array.isArray(evidenceIndex.entries) ? evidenceIndex.entries : [];
const counts = {};
for (const entry of entries) {
    const type = String(entry?.source_type ?? "unknown");
    counts[type] = (counts[type] ?? 0) + 1;
}
const blockingEvidence = entries.filter((entry) => String(entry?.status ?? "").toLowerCase() === "fail");
const finalReport = {
    artifact: "final_mission_report",
    generated_by: SCRIPT_ID,
    status: issues.length || blockingEvidence.length ? "blocked" : "complete",
    summary: "Final mission report generated from script-produced evidence artifacts.",
    evidence_index: ".ai/reports/evidence-index.yaml",
    evidence_refs: entries.map((entry) => entry.path).filter((value) => typeof value === "string"),
    evidence_counts_by_type: counts,
    validation_summary: {
        blocking_evidence_count: blockingEvidence.length,
        failed_evidence_refs: blockingEvidence.map((entry) => entry.path),
    },
    transition_evidence: {
        gates: entries.filter((entry) => entry.source_type === "gate").map((entry) => entry.path),
        handoffs: entries.filter((entry) => entry.source_type === "handoff").map((entry) => entry.path),
        revisions: entries.filter((entry) => entry.source_type === "revision").map((entry) => entry.path),
    },
    unresolved_issues: blockingEvidence.map((entry) => ({ source: entry.path, status: entry.status })),
};
writeYamlFile(path.join(root, ".ai", "reports", "final-mission-report.yaml"), finalReport);
writeYamlFile(path.join(root, ".ai", "reports", "mission-evidence-summary.yaml"), {
    artifact: "mission_evidence_summary",
    generated_by: SCRIPT_ID,
    status: finalReport.status,
    evidence_counts_by_type: counts,
    evidence_index: ".ai/reports/evidence-index.yaml",
});
finish(SCRIPT_ID, issues, [".ai/reports/final-mission-report.yaml", ".ai/reports/mission-evidence-summary.yaml"], {
    status: finalReport.status,
    evidence_count: entries.length,
});
